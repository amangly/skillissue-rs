//! Application palette shared by every GPUI Kit component.
use gpui_kit::{App, Hsla, component::Theme, rgb};

pub(crate) fn apply(cx: &mut App) {
    Theme::update(cx, |theme| {
        theme.font_family = "Segoe UI".into();
        let dark = theme.mode.is_dark();
        let color =
            |light, dark_value| -> Hsla { rgb(if dark { dark_value } else { light }).into() };
        let background = color(0xe1e8f4, 0x172236);
        let surface = color(0xeaf0f8, 0x213047);
        let hover = color(0xd5e3f3, 0x2a3b52);
        let active = color(0xc2d5ed, 0x344b69);
        let foreground = color(0x263246, 0xe5edf9);
        let muted = color(0x5c6a7d, 0xb9c7dc);
        let border = color(0xb3c1d4, 0x405064);
        let primary = color(0x2879d8, 0x8cbaff);
        let primary_hover = color(0x246dc2, 0xa4c9ff);
        let primary_active = color(0x205fa8, 0x72a8ef);
        let on_primary = color(0xffffff, 0x172236);
        theme.background = background;
        theme.sidebar = background;
        theme.tab_bar = background;
        theme.table = background;
        theme.status_bar = background;
        theme.popover = surface;
        theme.accordion = surface;
        theme.group_box = surface;
        theme.colors.list = surface;
        theme.list_even = surface;
        theme.list_head = surface;
        theme.table_even = surface;
        theme.table_head = surface;
        theme.table_foot = surface;
        theme.title_bar = surface;
        theme.tab = surface;
        theme.tab_bar_segmented = surface;
        theme.button = surface;
        theme.accent = hover;
        theme.button_hover = hover;
        theme.secondary_hover = hover;
        theme.list_hover = hover;
        theme.table_hover = hover;
        theme.sidebar_accent = hover;
        theme.tab_active = hover;
        theme.button_active = active;
        theme.secondary_active = active;
        theme.list_active = active;
        theme.table_active = active;
        theme.foreground = foreground;
        theme.accent_foreground = foreground;
        theme.button_foreground = foreground;
        theme.group_box_foreground = foreground;
        theme.popover_foreground = foreground;
        theme.secondary_foreground = foreground;
        theme.sidebar_foreground = foreground;
        theme.sidebar_accent_foreground = foreground;
        theme.tab_active_foreground = foreground;
        theme.table_head_foreground = foreground;
        theme.table_foot_foreground = foreground;
        theme.muted_foreground = muted;
        theme.tab_foreground = muted;
        theme.description_list_label_foreground = muted;
        theme.border = border;
        theme.input = border;
        theme.sidebar_border = border;
        theme.title_bar_border = border;
        theme.status_bar_border = border;
        theme.table_row_border = border;
        theme.window_border = border;
        theme.primary = primary;
        theme.button_primary = primary;
        theme.sidebar_primary = primary;
        theme.ring = primary;
        theme.caret = primary;
        theme.progress_bar = primary;
        theme.slider_bar = primary;
        theme.list_active_border = primary;
        theme.table_active_border = primary;
        theme.primary_hover = primary_hover;
        theme.button_primary_hover = primary_hover;
        theme.link_hover = primary_hover;
        theme.primary_active = primary_active;
        theme.button_primary_active = primary_active;
        theme.link_active = primary_active;
        theme.primary_foreground = on_primary;
        theme.button_primary_foreground = on_primary;
        theme.sidebar_primary_foreground = on_primary;
        theme.secondary = surface;
        theme.button_secondary = surface;
        theme.button_secondary_foreground = foreground;
        theme.button_secondary_hover = hover;
        theme.button_secondary_active = active;
        theme.muted = hover;
        theme.switch = border;
        theme.switch_thumb = foreground;
        theme.skeleton = hover;
        theme.slider_thumb = on_primary;
        theme.link = primary;
        theme.scrollbar = background;
        theme.scrollbar_thumb = border;
        theme.scrollbar_thumb_hover = muted;
        theme.selection = active;
        theme.description_list_label = surface;
        theme.chart_grid = border;
        theme.chart_1 = primary;
        theme.chart_2 = color(0x377b5d, 0x8adbb1);
        theme.chart_3 = color(0x8862b4, 0xc4a1ef);
        theme.chart_4 = color(0xab7834, 0xe9c07e);
        theme.chart_5 = color(0x398396, 0x85cbdc);
    });
}
